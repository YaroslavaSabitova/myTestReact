// OAuth - авторизация через внешние сервисы

import { useSearchParams, Navigate } from 'react-router-dom';

export const Auth = () => {
  // Получаем значение из SearchParams (часть URL после знака ?)

  // http://mysite.com/auth?authToken=abc123&userId=42
  // Search Params - всё, что идёт после знака ?
  const [searchParams] = useSearchParams();
  // authToken = abc123;
  const authToken = searchParams.get('authToken');

  // 1. Если токена нет (ошибка авторизации) — редирект на страницу входа
  if (!authToken) {
    return <Navigate to='/sign-in' replace />;
  }

  // 2. Если токен есть (успех) — автоматический редирект на главную страницу
  return <Navigate to='/' replace />;
};

// Пользователь нажимает «Войти через...» на каком-то сайте.

// Его перекидывает на внешний сервис (например, на сайт Google).

// Пользователь вводит там логин и пароль, нажимает «Разрешить».

// Внешний сервис перенаправляет его обратно в твое приложение по адресу http://твой-сайт/auth?authToken=секретный_токен_123.

// Срабатывает компонент Auth. Хук useSearchParams вытаскивает из адресной строки этот токен.

// Если токен есть (успех) → <Navigate to="/" /> перекидывает на главную.

// Если токена нет (ошибка) → <Navigate to="/sign-in" /> перекидывает на форму входа.

// Без replace текущая страница (/auth?authToken=...) останется в истории браузера.
// Пользователь нажмет кнопку «Назад» в браузере, и его снова перекинет на /auth, снова сработает редирект, и он застрянет в бесконечной петле.
// С replace мы говорим браузеру: «Замени текущую страницу в истории на новую, не сохраняй /auth в истории». Это избавляет от петли.
