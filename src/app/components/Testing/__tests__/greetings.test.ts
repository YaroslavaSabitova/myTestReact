import { describe, it, expect } from '@jest/globals';

import { greetings } from '../greetings';

describe('Тестирование функции greetings', () => {
  // 1. Проверяем неверные значения (выброс ошибки)
  describe('Неверные значения (должны выбрасывать ошибку)', () => {
    it('должна выбрасывать ошибку при отрицательном значении', () => {
      expect(() => greetings(-1)).toThrow('Неверное количество часов');
    });

    it('должна выбрасывать ошибку, если часов больше 23', () => {
      expect(() => greetings(24)).toThrow('Неверное количество часов');
    });

    // проверяем граничные значения ошибок
    it('должна выбрасывать ошибку при -100 и 100', () => {
      expect(() => greetings(-100)).toThrow();
      expect(() => greetings(100)).toThrow();
    });
  });

  // 2. Проверяем "Доброе утро!"
  describe('Утро (с 5 до 11)', () => {
    it("должна возвращать 'Доброе утро!' ровно в 5 часов (нижняя граница)", () => {
      expect(greetings(5)).toBe('Доброе утро!');
    });

    it("должна возвращать 'Доброе утро!' в 8 часов", () => {
      expect(greetings(8)).toBe('Доброе утро!');
    });

    it("должна возвращать 'Доброе утро!' в 11 часов (верхняя граница)", () => {
      expect(greetings(11)).toBe('Доброе утро!');
    });
  });

  // 3. Проверяем "Добрый день!"
  describe('День (с 12 до 17)', () => {
    it("должна возвращать 'Добрый день!' ровно в 12 часов (нижняя граница)", () => {
      expect(greetings(12)).toBe('Добрый день!');
    });

    it("должна возвращать 'Добрый день!' в 17 часов (верхняя граница)", () => {
      expect(greetings(17)).toBe('Добрый день!');
    });
  });

  // 4. Проверяем "Добрый вечер!"
  describe('Вечер (с 18 до 21)', () => {
    it("должна возвращать 'Добрый вечер!' ровно в 18 часов (нижняя граница)", () => {
      expect(greetings(18)).toBe('Добрый вечер!');
    });

    it("должна возвращать 'Добрый вечер!' в 21 час (верхняя граница)", () => {
      expect(greetings(21)).toBe('Добрый вечер!');
    });
  });

  // 5. Проверяем "Доброй ночи!"
  describe('Ночь (с 22 до 4)', () => {
    it("должна возвращать 'Доброй ночи!' ровно в 22 часа (начало ночи)", () => {
      expect(greetings(22)).toBe('Доброй ночи!');
    });

    it("должна возвращать 'Доброй ночи!' в 23 часа (конец дня)", () => {
      expect(greetings(23)).toBe('Доброй ночи!');
    });

    it("должна возвращать 'Доброй ночи!' ровно в 0 часов (начало новых суток)", () => {
      expect(greetings(0)).toBe('Доброй ночи!');
    });

    it("должна возвращать 'Доброй ночи!' в 4 часа (конец ночи)", () => {
      expect(greetings(4)).toBe('Доброй ночи!');
    });
  });
});
